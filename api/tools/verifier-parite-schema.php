#!/usr/bin/env php
<?php

/**
 * Vérificateur de parité des TROIS schémas — garde-fou de la CI.
 *
 * Des schémas maintenus à la main finissent toujours par diverger (PLAN.md).
 * Ce script compare `schema.sqlite.sql`, `schema.mysql.sql` et
 * `schema.pgsql.sql` sur :
 *   - la liste des tables ET leur ordre ;
 *   - pour chaque table, la liste des colonnes, leur ordre, leur type
 *     canonique, leur nullabilité, leur clé, leur valeur par défaut ;
 *   - la liste des index, leur table et leurs colonnes.
 *
 * SQLite sert de référence : chaque autre dialecte lui est comparé, ce qui
 * rend transitive la parité des trois. Le script sort en code 1 à la moindre
 * divergence, avec la liste des écarts et le couple de fichiers concerné.
 *
 * Usage :
 *   php api/tools/verifier-parite-schema.php
 *
 * Correspondance de types — les seules tolérances admises :
 *   sqlite TEXT             <-> mysql VARCHAR(n) | TEXT | LONGTEXT | MEDIUMTEXT
 *                           <-> pgsql VARCHAR(n) | TEXT
 *   sqlite TEXT /* JSON *\/ <-> mysql JSON
 *                           <-> pgsql TEXT /* JSON *\/   (jsonb écarté, cf. schéma)
 *   sqlite INTEGER          <-> mysql INT | BIGINT | TINYINT | SMALLINT
 *                           <-> pgsql INTEGER | BIGINT | SMALLINT
 *   sqlite REAL             <-> mysql DOUBLE | FLOAT | DECIMAL(n,m)
 *                           <-> pgsql REAL | DOUBLE PRECISION | NUMERIC
 * Les longueurs VARCHAR ne sont pas comparées : SQLite n'en a pas.
 *
 * Auto-incrément, une écriture par dialecte, toutes trois reconnues :
 *   sqlite INTEGER PRIMARY KEY AUTOINCREMENT
 *   mysql  BIGINT AUTO_INCREMENT PRIMARY KEY
 *   pgsql  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
 */

declare(strict_types=1);

$racine = dirname(__DIR__);

/** Dialecte → fichier. L'ordre fixe celui des comparaisons et de l'affichage. */
$fichiers = [
    'sqlite' => $racine . '/schema/schema.sqlite.sql',
    'mysql' => $racine . '/schema/schema.mysql.sql',
    'pgsql' => $racine . '/schema/schema.pgsql.sql',
];

foreach ($fichiers as $f) {
    if (!is_file($f)) {
        fwrite(STDERR, "ERREUR : fichier de schéma introuvable : {$f}\n");
        exit(1);
    }
}

$schemas = [];
foreach ($fichiers as $dialecte => $f) {
    $schemas[$dialecte] = analyser((string) file_get_contents($f), $dialecte);
}

// SQLite est la référence : comparer chaque autre dialecte à elle suffit à
// garantir la parité du triplet, et nomme sans ambiguïté le fichier fautif.
$ecarts = [];
foreach (['mysql', 'pgsql'] as $dialecte) {
    foreach (comparer($schemas['sqlite'], $schemas[$dialecte], 'sqlite', $dialecte) as $e) {
        $ecarts[] = $e;
    }
}

if ($ecarts !== []) {
    fwrite(STDERR, "PARITÉ DE SCHÉMA ROMPUE — " . count($ecarts) . " écart(s) :\n");
    foreach ($ecarts as $e) {
        fwrite(STDERR, "  - {$e}\n");
    }
    fwrite(STDERR, "\nCorrigez les TROIS fichiers de schema/ puis relancez.\n");
    exit(1);
}

$nbTables = count($schemas['sqlite']['tables']);
$nbColonnes = array_sum(array_map(static fn (array $t): int => count($t), $schemas['sqlite']['tables']));
$nbIndex = count($schemas['sqlite']['index']);
$nbSchemas = count($fichiers);

echo "PARITÉ OK — {$nbTables} tables, {$nbColonnes} colonnes, {$nbIndex} index identiques "
    . "dans les {$nbSchemas} schémas (" . implode(', ', array_keys($fichiers)) . ").\n";
exit(0);

// =====================================================================
// Analyse
// =====================================================================

/**
 * @return array{tables: array<string,array<string,array<string,mixed>>>, ordreTables: string[], index: array<string,array{table:string,colonnes:string[]}>}
 */
function analyser(string $sql, string $dialecte): array
{
    // Les commentaires de ligne `--` disparaissent, mais PAS les blocs
    // `/* JSON */` qui portent l'intention de type côté SQLite.
    $sql = preg_replace('/^\s*--.*$/m', '', $sql) ?? $sql;

    $tables = [];
    $ordreTables = [];
    $index = [];

    // ---- Tables ----
    $offset = 0;
    while (preg_match(
        '/CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`"]?([A-Za-z0-9_]+)[`"]?\s*\(/i',
        $sql,
        $m,
        PREG_OFFSET_CAPTURE,
        $offset
    ) === 1) {
        $nom = strtolower($m[1][0]);
        $debut = $m[0][1] + strlen($m[0][0]); // juste après la parenthèse ouvrante
        $fin = trouverParentheseFermante($sql, $debut);
        if ($fin === null) {
            fwrite(STDERR, "ERREUR d'analyse ({$dialecte}) : parenthèse non fermée pour la table « {$nom} ».\n");
            exit(1);
        }
        $corps = substr($sql, $debut, $fin - $debut);
        $tables[$nom] = analyserColonnes($corps, $dialecte, $nom);
        $ordreTables[] = $nom;
        $offset = $fin + 1;
    }

    // ---- Index ----
    if (preg_match_all(
        '/CREATE\s+(UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?[`"]?([A-Za-z0-9_]+)[`"]?\s+ON\s+[`"]?([A-Za-z0-9_]+)[`"]?\s*\(([^)]*)\)/i',
        $sql,
        $tous,
        PREG_SET_ORDER
    ) > 0) {
        foreach ($tous as $m) {
            $nomIndex = strtolower($m[2]);
            $colonnes = array_map(
                static fn (string $c): string => strtolower(trim($c, " \t\n`\"")),
                explode(',', $m[4])
            );
            $index[$nomIndex] = [
                'table' => strtolower($m[3]),
                'colonnes' => $colonnes,
                'unique' => trim($m[1]) !== '',
            ];
        }
    }

    return ['tables' => $tables, 'ordreTables' => $ordreTables, 'index' => $index];
}

function trouverParentheseFermante(string $sql, int $depuis): ?int
{
    $profondeur = 1;
    $len = strlen($sql);
    for ($i = $depuis; $i < $len; $i++) {
        $c = $sql[$i];
        if ($c === "'") {
            // Saute la chaîne littérale (les DEFAULT '' et 'pending').
            $i++;
            while ($i < $len && $sql[$i] !== "'") {
                $i++;
            }
            continue;
        }
        if ($c === '(') {
            $profondeur++;
        } elseif ($c === ')') {
            $profondeur--;
            if ($profondeur === 0) {
                return $i;
            }
        }
    }

    return null;
}

/**
 * @return array<string,array<string,mixed>> colonne → descripteur canonique
 */
function analyserColonnes(string $corps, string $dialecte, string $table): array
{
    $colonnes = [];
    foreach (decouperNiveauUn($corps) as $ligne) {
        $ligne = trim($ligne);
        if ($ligne === '') {
            continue;
        }
        // Contraintes de table (PRIMARY KEY (...), FOREIGN KEY, UNIQUE (...)) :
        // aucune n'est utilisée dans ce projet, on refuse pour rester lisible.
        if (preg_match('/^(PRIMARY\s+KEY|FOREIGN\s+KEY|UNIQUE\s*\(|CONSTRAINT|KEY\s|INDEX\s)/i', $ligne) === 1) {
            fwrite(STDERR, "ERREUR ({$dialecte}, table {$table}) : contrainte de table non supportée par le "
                . "vérificateur : « {$ligne} ». Déclarez-la en ligne sur la colonne.\n");
            exit(1);
        }

        // Marqueur d'intention JSON côté SQLite, puis retrait des commentaires.
        $marqueJson = stripos($ligne, '/* JSON */') !== false;
        $ligne = trim((string) preg_replace('#/\*.*?\*/#s', ' ', $ligne));

        if (preg_match('/^[`"]?([A-Za-z0-9_]+)[`"]?\s+(.*)$/s', $ligne, $m) !== 1) {
            continue;
        }
        $nom = strtolower($m[1]);
        $reste = trim((string) preg_replace('/\s+/', ' ', $m[2]));

        // Type : premier jeton, éventuellement suivi de (n) ou (n,m).
        if (preg_match('/^([A-Za-z]+)(\s*\([0-9,\s]*\))?\s*(.*)$/s', $reste, $t) !== 1) {
            continue;
        }
        $typeBrut = strtoupper($t[1]);
        $drapeaux = strtoupper(trim($t[3]));

        // Auto-incrément : trois écritures pour la même intention.
        // `GENERATED BY DEFAULT AS IDENTITY` (PostgreSQL) est RETIRÉ des
        // drapeaux une fois reconnu — sans quoi son « BY DEFAULT » serait lu
        // comme une valeur par défaut « AS » par extraireDefaut(), et toutes les
        // colonnes d'identité seraient déclarées divergentes.
        $auto = preg_match('/\bAUTO_?INCREMENT\b/i', $drapeaux) === 1
            || preg_match('/\bGENERATED\s+(BY\s+DEFAULT|ALWAYS)\s+AS\s+IDENTITY\b/i', $drapeaux) === 1;
        $drapeaux = (string) preg_replace(
            '/\bGENERATED\s+(BY\s+DEFAULT|ALWAYS)\s+AS\s+IDENTITY\b/i',
            ' ',
            $drapeaux
        );

        $colonnes[$nom] = [
            'type' => typeCanonique($typeBrut, $marqueJson, $dialecte, $table, $nom),
            'nullable' => stripos($drapeaux, 'NOT NULL') === false,
            'pk' => stripos($drapeaux, 'PRIMARY KEY') !== false,
            'unique' => (bool) preg_match('/\bUNIQUE\b/i', $drapeaux),
            'auto' => $auto,
            'defaut' => extraireDefaut($drapeaux),
        ];
    }

    return $colonnes;
}

/** Découpe sur les virgules de niveau 1 (hors parenthèses et hors chaînes). */
function decouperNiveauUn(string $corps): array
{
    $parts = [];
    $courant = '';
    $profondeur = 0;
    $len = strlen($corps);
    for ($i = 0; $i < $len; $i++) {
        $c = $corps[$i];
        if ($c === "'") {
            $courant .= $c;
            $i++;
            while ($i < $len && $corps[$i] !== "'") {
                $courant .= $corps[$i];
                $i++;
            }
            $courant .= "'";
            continue;
        }
        if ($c === '(') {
            $profondeur++;
        } elseif ($c === ')') {
            $profondeur--;
        }
        if ($c === ',' && $profondeur === 0) {
            $parts[] = $courant;
            $courant = '';
            continue;
        }
        $courant .= $c;
    }
    if (trim($courant) !== '') {
        $parts[] = $courant;
    }

    return $parts;
}

function typeCanonique(string $type, bool $marqueJson, string $dialecte, string $table, string $colonne): string
{
    // SQLite et PostgreSQL portent tous deux le JSON dans une colonne TEXT :
    // le marqueur `/* JSON */` est donc leur SEUL porteur d'intention de type,
    // et son absence sur une colonne JSON est une divergence, pas un détail.
    if ($dialecte === 'sqlite' || $dialecte === 'pgsql') {
        if ($marqueJson) {
            if ($type !== 'TEXT') {
                fwrite(STDERR, "ERREUR ({$dialecte}, {$table}.{$colonne}) : marqueur /* JSON */ posé sur un "
                    . "type « {$type} » ; il doit l'être sur TEXT.\n");
                exit(1);
            }

            return 'json';
        }
    }

    if ($dialecte === 'sqlite') {
        return match ($type) {
            'TEXT' => 'text',
            'INTEGER' => 'int',
            'REAL' => 'real',
            'BLOB' => 'blob',
            default => erreurType($dialecte, $table, $colonne, $type),
        };
    }

    if ($dialecte === 'pgsql') {
        return match ($type) {
            // `jsonb` est volontairement absent de cette table : le schéma
            // PostgreSQL stocke le JSON en TEXT, et dit pourquoi en tête de
            // fichier. Un `jsonb` qui apparaîtrait ici serait donc refusé, ce
            // qui est l'effet recherché tant que le choix n'est pas rouvert.
            'VARCHAR', 'CHAR', 'TEXT' => 'text',
            'SMALLINT', 'INTEGER', 'INT', 'BIGINT' => 'int',
            'REAL', 'DOUBLE', 'NUMERIC', 'DECIMAL' => 'real',
            'BYTEA' => 'blob',
            default => erreurType($dialecte, $table, $colonne, $type),
        };
    }

    return match ($type) {
        'JSON' => 'json',
        'VARCHAR', 'CHAR', 'TEXT', 'TINYTEXT', 'MEDIUMTEXT', 'LONGTEXT' => 'text',
        'INT', 'INTEGER', 'BIGINT', 'TINYINT', 'SMALLINT', 'MEDIUMINT' => 'int',
        'DOUBLE', 'FLOAT', 'DECIMAL', 'NUMERIC' => 'real',
        'BLOB', 'LONGBLOB', 'MEDIUMBLOB' => 'blob',
        default => erreurType($dialecte, $table, $colonne, $type),
    };
}

function erreurType(string $dialecte, string $table, string $colonne, string $type): string
{
    fwrite(STDERR, "ERREUR ({$dialecte}, {$table}.{$colonne}) : type « {$type} » non reconnu par le "
        . "vérificateur de parité. Ajoutez-le à la table de correspondance de ce script si c'est voulu.\n");
    exit(1);
}

/** Extrait et normalise la valeur par défaut, ou null s'il n'y en a pas. */
function extraireDefaut(string $drapeaux): ?string
{
    if (preg_match("/\bDEFAULT\s+('(?:[^']*)'|[A-Za-z0-9_.\-+]+)/i", $drapeaux, $m) !== 1) {
        return null;
    }
    $v = trim($m[1]);
    if (str_starts_with($v, "'")) {
        return "'" . trim($v, "'") . "'";
    }

    return strtoupper($v);
}

