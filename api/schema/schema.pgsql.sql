-- =====================================================================
-- KA Tech Hub — schéma PostgreSQL (PostgreSQL 12+, Supabase, Neon, Railway)
-- =====================================================================
-- TRIPLÉ OBLIGATOIRE de api/schema/schema.sqlite.sql et de
-- api/schema/schema.mysql.sql. Toute modification ici doit être reportée dans
-- les DEUX autres, dans le MÊME ORDRE :
-- `php api/tools/verifier-parite-schema.php` échoue sinon, et la CI avec lui.
--
-- Correspondances de types imposées par le vérificateur de parité :
--   TEXT (sqlite)            <-> VARCHAR(n) | TEXT
--   TEXT /* JSON */ (sqlite) <-> TEXT /* JSON */   (voir « JSON » ci-dessous)
--   INTEGER (sqlite)         <-> INTEGER | BIGINT | SMALLINT
--   ... PRIMARY KEY AUTOINCREMENT <-> BIGINT GENERATED BY DEFAULT AS IDENTITY
--
-- Trois choix de dialecte, et leurs raisons — les rouvrir demande de relire
-- api/src/Db.php, qui les documente côté code :
--
--   * JSON en TEXT, et NON en `jsonb`. `jsonb` réordonne les clés et retire les
--     espaces : la chaîne relue ne serait plus celle écrite par `Db::json()`, et
--     les trois pilotes cesseraient d'être interchangeables. Surtout, le
--     catalogue filtre avec `use_tags LIKE '%"work"%'` et `LOWER(name) LIKE …`,
--     or PostgreSQL n'a ni `LIKE` ni `LOWER()` sur `jsonb` (« operator does not
--     exist: jsonb ~~ unknown »). Le marqueur `/* JSON */` est conservé : c'est
--     lui que lit le vérificateur de parité, et il porte l'intention de type.
--
--   * Booléens en SMALLINT 0/1, et NON en `boolean` natif. PostgreSQL est
--     strictement typé et ne compare pas un entier à un booléen : les 70 routes
--     qui écrivent `WHERE best_seller = :b` avec `1` tomberaient en « column is
--     of type boolean but expression is of type integer ». Le contrat du projet
--     est « INTEGER 0/1 en base, vrai booléen dans le DTO » (docs/BACKEND.md §4)
--     et il vaut pour les trois pilotes.
--
--   * Auto-incréments en `GENERATED BY DEFAULT AS IDENTITY` plutôt qu'en
--     `serial`. `serial` est un raccourci historique qui crée une séquence
--     détachée de la colonne ; `IDENTITY` est la forme normalisée SQL, et
--     « BY DEFAULT » (et non « ALWAYS ») laisse un import de données fournir
--     explicitement un id, ce dont `api/tools/importer-donnees-front.php` a
--     besoin.
--
-- Aucune contrainte de table (`PRIMARY KEY (...)`, `FOREIGN KEY`) : tout est
-- déclaré en ligne sur la colonne, comme dans les deux autres schémas. Le
-- vérificateur de parité refuse explicitement les contraintes de table.
-- =====================================================================

-- ---------------------------------------------------------------- 01
CREATE TABLE IF NOT EXISTS categories (
  slug          VARCHAR(64) NOT NULL PRIMARY KEY,
  label         VARCHAR(191) NOT NULL,
  description   TEXT NOT NULL,
  cover         VARCHAR(512) NULL,
  position      INTEGER NOT NULL DEFAULT 0,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 02
CREATE TABLE IF NOT EXISTS brands (
  id            VARCHAR(64) NOT NULL PRIMARY KEY,
  name          VARCHAR(191) NOT NULL,
  description   TEXT NULL,
  country       VARCHAR(96) NULL,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 03
CREATE TABLE IF NOT EXISTS products (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  name          TEXT /* JSON */ NOT NULL,
  brand         VARCHAR(96) NOT NULL DEFAULT '',
  category      VARCHAR(64) NOT NULL,
  use_tags      TEXT /* JSON */ NOT NULL,
  spec_line     TEXT /* JSON */ NULL,
  specs         TEXT /* JSON */ NULL,
  price         INTEGER NOT NULL DEFAULT 0,
  old_price     INTEGER NULL,
  stock         VARCHAR(16) NOT NULL DEFAULT 'in',
  stock_qty     INTEGER NULL,
  image         VARCHAR(512) NOT NULL DEFAULT '',
  best_seller   SMALLINT NOT NULL DEFAULT 0,
  sale          SMALLINT NOT NULL DEFAULT 0,
  custom_build  SMALLINT NOT NULL DEFAULT 0,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_products_category ON products (category);
CREATE INDEX IF NOT EXISTS idx_products_brand ON products (brand);
CREATE INDEX IF NOT EXISTS idx_products_price ON products (price);
CREATE INDEX IF NOT EXISTS idx_products_catalogue ON products (custom_build, category);

-- ---------------------------------------------------------------- 04
CREATE TABLE IF NOT EXISTS customers (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  name          VARCHAR(191) NOT NULL,
  email         VARCHAR(191) NOT NULL DEFAULT '',
  phone         VARCHAR(48) NOT NULL DEFAULT '',
  wilaya        VARCHAR(64) NOT NULL DEFAULT '',
  orders_count  INTEGER NOT NULL DEFAULT 0,
  total_spent   INTEGER NOT NULL DEFAULT 0,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_customers_email ON customers (email);

-- ---------------------------------------------------------------- 05
CREATE TABLE IF NOT EXISTS orders (
  id              VARCHAR(64) NOT NULL PRIMARY KEY,
  customer_id     VARCHAR(96) NULL,
  customer_name   VARCHAR(191) NOT NULL,
  customer_email  VARCHAR(191) NULL,
  subtotal        INTEGER NOT NULL DEFAULT 0,
  discount        INTEGER NOT NULL DEFAULT 0,
  coupon_code     VARCHAR(64) NULL,
  shipping        INTEGER NOT NULL DEFAULT 0,
  total           INTEGER NOT NULL DEFAULT 0,
  status          VARCHAR(24) NOT NULL DEFAULT 'pending',
  status_history  TEXT /* JSON */ NOT NULL,
  payment_method  VARCHAR(64) NOT NULL DEFAULT '',
  payment_label   VARCHAR(191) NULL,
  wilaya          VARCHAR(64) NOT NULL DEFAULT '',
  delivery_kind   VARCHAR(16) NOT NULL DEFAULT 'home',
  address         TEXT NOT NULL,
  phone           VARCHAR(48) NOT NULL DEFAULT '',
  note                TEXT NULL,
  invoice_snapshot    TEXT /* JSON */ NULL,
  created_at          VARCHAR(32) NOT NULL,
  updated_at          VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders (status);
CREATE INDEX IF NOT EXISTS idx_orders_created ON orders (created_at);

-- ---------------------------------------------------------------- 06
-- Lignes de commande : `name` est une EMPREINTE, chaîne simple figée à
-- l'écriture. Ne jamais la relire depuis products.
CREATE TABLE IF NOT EXISTS order_items (
  id            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  order_id      VARCHAR(64) NOT NULL,
  product_id    VARCHAR(96) NOT NULL,
  name          VARCHAR(255) NOT NULL,
  price         INTEGER NOT NULL DEFAULT 0,
  qty           INTEGER NOT NULL DEFAULT 1,
  image         VARCHAR(512) NULL,
  position      INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items (order_id);
CREATE INDEX IF NOT EXISTS idx_order_items_product ON order_items (product_id);

-- ---------------------------------------------------------------- 07
CREATE TABLE IF NOT EXISTS coupons (
  code          VARCHAR(64) NOT NULL PRIMARY KEY,
  type          VARCHAR(16) NOT NULL DEFAULT 'percent',
  value         INTEGER NOT NULL DEFAULT 0,
  min_purchase  INTEGER NOT NULL DEFAULT 0,
  expires_at    VARCHAR(32) NULL,
  usage_count   INTEGER NOT NULL DEFAULT 0,
  usage_limit   INTEGER NOT NULL DEFAULT 0,
  active        SMALLINT NOT NULL DEFAULT 1,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 08
CREATE TABLE IF NOT EXISTS reviews (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  product_id    VARCHAR(96) NOT NULL,
  product_name  VARCHAR(255) NOT NULL,
  customer_name VARCHAR(191) NOT NULL,
  rating        INTEGER NOT NULL DEFAULT 5,
  title         VARCHAR(255) NOT NULL DEFAULT '',
  body          TEXT NOT NULL,
  status        VARCHAR(16) NOT NULL DEFAULT 'pending',
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_reviews_product ON reviews (product_id);
CREATE INDEX IF NOT EXISTS idx_reviews_status ON reviews (status);

-- ---------------------------------------------------------------- 09
CREATE TABLE IF NOT EXISTS users (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  name          VARCHAR(191) NOT NULL DEFAULT '',
  email         VARCHAR(191) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role          VARCHAR(24) NOT NULL DEFAULT 'customer',
  active        SMALLINT NOT NULL DEFAULT 1,
  phone         VARCHAR(48) NULL,
  last_login    VARCHAR(32) NULL,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);

-- ---------------------------------------------------------------- 10
CREATE TABLE IF NOT EXISTS blog_posts (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  slug          VARCHAR(191) NOT NULL UNIQUE,
  title         TEXT /* JSON */ NOT NULL,
  excerpt       TEXT /* JSON */ NULL,
  content       TEXT /* JSON */ NULL,
  cover         VARCHAR(512) NULL,
  author        VARCHAR(191) NOT NULL DEFAULT '',
  tags          TEXT /* JSON */ NOT NULL,
  status        VARCHAR(16) NOT NULL DEFAULT 'draft',
  published_at  VARCHAR(32) NULL,
  created_at    VARCHAR(32) NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_blog_posts_status ON blog_posts (status);

-- ---------------------------------------------------------------- 11
CREATE TABLE IF NOT EXISTS media_assets (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  name          VARCHAR(255) NOT NULL,
  src           TEXT NOT NULL,
  mime          VARCHAR(128) NOT NULL DEFAULT '',
  size          INTEGER NOT NULL DEFAULT 0,
  tag           VARCHAR(64) NULL,
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_media_assets_tag ON media_assets (tag);

-- ---------------------------------------------------------------- 12
-- `is_read` et non `read` : READ est un mot réservé MySQL.
CREATE TABLE IF NOT EXISTS notifications (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  title         VARCHAR(255) NOT NULL,
  body          TEXT NOT NULL,
  level         VARCHAR(16) NOT NULL DEFAULT 'info',
  is_read       SMALLINT NOT NULL DEFAULT 0,
  link          VARCHAR(512) NULL,
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_notifications_read ON notifications (is_read);

-- ---------------------------------------------------------------- 13
CREATE TABLE IF NOT EXISTS messages (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  name          VARCHAR(191) NOT NULL,
  email         VARCHAR(191) NOT NULL DEFAULT '',
  phone         VARCHAR(48) NULL,
  subject       VARCHAR(255) NOT NULL DEFAULT '',
  body          TEXT NOT NULL,
  is_read       SMALLINT NOT NULL DEFAULT 0,
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_messages_read ON messages (is_read);

-- ---------------------------------------------------------------- 14
CREATE TABLE IF NOT EXISTS subscribers (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  email         VARCHAR(191) NOT NULL UNIQUE,
  source        VARCHAR(64) NULL,
  created_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 15
-- `wilaya_code` vaut « * » pour le tarif par défaut.
CREATE TABLE IF NOT EXISTS shipping_rates (
  wilaya_code   VARCHAR(8) NOT NULL PRIMARY KEY,
  home          INTEGER NOT NULL DEFAULT 0,
  desk          INTEGER NOT NULL DEFAULT 0,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 16
CREATE TABLE IF NOT EXISTS payment_methods (
  id            VARCHAR(64) NOT NULL PRIMARY KEY,
  label         VARCHAR(191) NOT NULL,
  instructions  TEXT NOT NULL,
  active        SMALLINT NOT NULL DEFAULT 1,
  position      INTEGER NOT NULL DEFAULT 0,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 17
-- `product_name` : EMPREINTE en chaîne simple, figée à l'écriture.
CREATE TABLE IF NOT EXISTS stock_movements (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  product_id    VARCHAR(96) NOT NULL,
  product_name  VARCHAR(255) NOT NULL DEFAULT '',
  delta         INTEGER NOT NULL DEFAULT 0,
  reason        VARCHAR(255) NOT NULL DEFAULT '',
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_stock_movements_product ON stock_movements (product_id);
CREATE INDEX IF NOT EXISTS idx_stock_movements_created ON stock_movements (created_at);

-- ---------------------------------------------------------------- 18
-- Contenu éditorial : une ligne par section (`home`, `about`, `footer`,
-- `home-reviews`, `ticker`, `builder`…), charge utile JSON semi-structurée.
CREATE TABLE IF NOT EXISTS site_content (
  section       VARCHAR(64) NOT NULL PRIMARY KEY,
  payload       TEXT /* JSON */ NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 19
-- Réglages : une ligne par portée (`site`, `shipping`).
CREATE TABLE IF NOT EXISTS settings (
  scope         VARCHAR(64) NOT NULL PRIMARY KEY,
  payload       TEXT /* JSON */ NOT NULL,
  updated_at    VARCHAR(32) NOT NULL
);

-- ---------------------------------------------------------------- 20
CREATE TABLE IF NOT EXISTS audit_logs (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  actor         VARCHAR(191) NOT NULL DEFAULT 'système',
  action        VARCHAR(128) NOT NULL,
  entity        VARCHAR(191) NOT NULL DEFAULT '',
  detail        TEXT NULL,
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_audit_logs_created ON audit_logs (created_at);
CREATE INDEX IF NOT EXISTS idx_audit_logs_action ON audit_logs (action);

-- ---------------------------------------------------------------- 21
-- Outbox : effets de bord différés (emails, webhooks) écrits dans la MÊME
-- transaction que le fait métier, dépilés ensuite par un cron.
CREATE TABLE IF NOT EXISTS outbox (
  id            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  topic         VARCHAR(128) NOT NULL,
  payload       TEXT /* JSON */ NOT NULL,
  status        VARCHAR(16) NOT NULL DEFAULT 'pending',
  attempts      INTEGER NOT NULL DEFAULT 0,
  last_error    TEXT NULL,
  available_at  VARCHAR(32) NOT NULL,
  processed_at  VARCHAR(32) NULL,
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_outbox_pending ON outbox (status, available_at);

-- ---------------------------------------------------------------- 22
-- Jetons de réinitialisation de mot de passe (vague 4.3).
-- On ne stocke QUE l'empreinte SHA-256 du secret : une fuite de cette table ne
-- permet donc pas de réinitialiser un compte. `used_at` rend le jeton à usage
-- unique ; `expires_at` en borne la durée de vie.
CREATE TABLE IF NOT EXISTS password_resets (
  id            VARCHAR(96) NOT NULL PRIMARY KEY,
  user_id       VARCHAR(96) NOT NULL,
  token_hash    VARCHAR(128) NOT NULL,
  expires_at    VARCHAR(32) NOT NULL,
  used_at       VARCHAR(32) NULL,
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_password_resets_user ON password_resets (user_id);
CREATE INDEX IF NOT EXISTS idx_password_resets_expires ON password_resets (expires_at);

-- ---------------------------------------------------------------- 23
-- Tentatives de connexion — limitation de débit (vague 4.5).
-- On ne stocke QUE le hash SHA-256 de l'IP et de l'email (champ `cle`) :
-- une fuite de cette table ne révèle ni adresses IP ni emails.
-- Les lignes expirées sont purgées par le CRON.
CREATE TABLE IF NOT EXISTS login_attempts (
  id            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  axe           VARCHAR(16) NOT NULL,
  cle           VARCHAR(64) NOT NULL,
  action        VARCHAR(64) NOT NULL DEFAULT 'login',
  created_at    VARCHAR(32) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_login_attempts_axe_cle ON login_attempts (axe, cle, action, created_at);
